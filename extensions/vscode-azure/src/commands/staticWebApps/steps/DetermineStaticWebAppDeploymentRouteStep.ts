import { IVsCode, PromptStep } from '@microsoft/vscode-azure-utils';
import { inject, injectable } from 'inversify';
import type * as vscode from 'vscode';
import { IAzdService, MinAzdPipelineVersion } from '../../../azd/AzdService';
import { IGitRemoteService } from '../../../staticWebApps/GitRemoteService';
import type { CreateStaticWebAppContext } from '../CreateStaticWebAppContext';
import { getStaticWebAppServiceConfig, hasConflictingProviderWorkflow, resolveStaticWebAppServiceProjectFolder, type StaticWebAppAutoDeployEligibility } from '../deploymentRouting';
import { canAzdDeployStaticWebApp } from './locationUtils';
import { detectStaticWebAppProject } from './frameworkDetection';
import { IWorkspaceIndexService } from '../../../utils/workspaceIndex/WorkspaceIndexService';

/**
 * Silently routes Static Web Apps deployment during creation, without ever
 * showing UI (modeled on {@linkcode import('../../../azd/wizard/HydrateAzdInfoStep').HydrateAzdInfoStep HydrateAzdInfoStep}).
 * Runs last in `CreateStaticWebApp`'s prompt steps, once `iacFolder`,
 * `outputLocation` (when captured this run), and `buildPresetSelection` are
 * already settled.
 *
 * **Direct deployment support is determined first, before any routing
 * decision.** Two independent signals gate it:
 * - Next.js hybrid/SSR is never deployable this way -- even if the user
 *   overrides the output location to a non-empty custom value, `azd deploy`
 *   still cannot serve server-rendered content, and the workflow generated by
 *   `azd pipeline config` only runs `azd deploy` too, so CI/CD cannot help
 *   either. Until a native SSR-capable workflow exists, both direct deploy
 *   *and* CI/CD are treated as unavailable for this shape. For a **fresh**
 *   wizard run this reads `context.buildPresetSelection === 'nextjs'`
 *   directly (`PickBuildPresetStep` already ran). For an **already-hydrated**
 *   project (`PickBuildPresetStep`/`OutputLocationStep` both skip once
 *   `infra/main.bicep` already exists, so `buildPresetSelection` is `undefined`
 *   and cannot be trusted), it is instead detected fresh via
 *   `detectStaticWebAppProject`, scoped to the existing service's `project`
 *   folder when known (never a repository-wide scan when a specific project
 *   path is already available from `azure.yaml`).
 * - Whether the artifact directory is distinct from source
 *   (`canAzdDeployStaticWebApp`). For a fresh run this reads
 *   `context.outputLocation` directly. For a hydrated project it is derived
 *   instead from the existing `azure.yaml`'s `host: staticwebapp` service
 *   `dist` -- a hydrated project must never be blanket-classified as
 *   unsupported just because this run didn't ask about output location. If no
 *   such service can be found at all (absent, unreadable, or an invalid
 *   `dist` -- missing/non-string/empty/`.`/`/`), eligibility is **not**
 *   granted: there is no valid deploy target to route direct deploy or CI/CD
 *   against. Eligibility is only ever derived from a positively-found, valid
 *   service.
 *
 * The two signals resolve to a {@linkcode StaticWebAppAutoDeployEligibility}
 * (`'supported' | 'hybridSsr' | 'invalidServiceConfig'`) so
 * `CreateStaticWebApp` can show honest, reason-specific guidance instead of
 * one generic message that might misdescribe a plain misconfiguration as
 * Next.js-specific (or vice versa).
 *
 * Decision (mutually exclusive):
 * 1. Neither direct deploy nor CI/CD is possible (either gate above) --
 *    explicitly forces `deploy: false` and sets
 *    {@linkcode CreateStaticWebAppContext.deploymentUnsupportedArtifactReason}
 *    so `CreateStaticWebApp` shows an honest, reason-specific "provisioned
 *    only" message instead of silently doing nothing or attempting a deploy
 *    that cannot work. This is a defensive, explicit suppression -- it does
 *    not rely on `OutputLocationStep`'s existing (still correct) gating as an
 *    implicit assumption, and it never even inspects the Git remote
 *    (irrelevant here).
 * 2. Direct deployment is supported, and a supported/pushed Git remote, a
 *    sufficient `azd` version, and no conflicting workflow for the other
 *    provider are all true -- sets `deploy: false` and
 *    {@linkcode CreateStaticWebAppContext.deploymentRoute}. `AzdDeployStep` is
 *    naturally skipped by the `deploy: false` merge; no changes to that
 *    shared step are needed.
 * 3. Direct deployment is supported, but CI/CD is not currently eligible
 *    (missing/unsupported remote, unpushed branch, `azd` too old, or a
 *    provider conflict) -- returns `{}`, retaining whatever `deploy` already
 *    was (`true`), so `AzdDeployStep` runs direct deploy exactly as it does
 *    today. This is the case (and the only case) where silently falling back
 *    to direct deploy is valid.
 */
@injectable()
export class DetermineStaticWebAppDeploymentRouteStep extends PromptStep<CreateStaticWebAppContext> {
    public constructor(
        @inject(IVsCode) private readonly code: IVsCode,
        @inject(IGitRemoteService) private readonly gitRemote: IGitRemoteService,
        @inject(IAzdService) private readonly azd: IAzdService,
        @inject(IWorkspaceIndexService) private readonly indexService: IWorkspaceIndexService,
    ) {
        super();
    }

    public override shouldPrompt(context: Readonly<CreateStaticWebAppContext>): boolean {
        return context.job === 'deploy' && !!context.iacFolder;
    }

    public async prompt(context: Readonly<CreateStaticWebAppContext>): Promise<Partial<CreateStaticWebAppContext>> {
        // shouldPrompt guarantees iacFolder is set.
        // eslint-disable-next-line @typescript-eslint/no-non-null-assertion
        const iacFolder = context.iacFolder!;

        const eligibility = await this.resolveEligibility(context, iacFolder);
        if (eligibility !== 'supported') {
            // Neither direct deploy nor CI/CD works for this artifact shape --
            // the Git remote is irrelevant, so it's never even inspected.
            return { deploy: false, deploymentUnsupportedArtifactReason: eligibility };
        }

        const remote = await this.gitRemote.getRemoteInfo(iacFolder);
        if (!remote || remote.provider === 'unsupported' || !remote.hasUpstream) {
            return {};
        }
        if (!await this.azd.checkVersion(MinAzdPipelineVersion)) {
            return {};
        }
        if (await hasConflictingProviderWorkflow(this.code, iacFolder, remote.provider)) {
            return {};
        }

        return {
            deploy: false,
            deploymentRoute: { provider: remote.provider, repositoryUrl: remote.url, branch: remote.branch },
        };
    }

    /**
     * Resolves overall auto-deploy eligibility. Framework/hybrid-SSR status is
     * checked ahead of artifact-shape (`dist`) validity, since Next.js
     * hybrid/SSR is an independent, architectural reason unrelated to whether
     * a `dist` happens to look valid -- a hybrid/SSR project is always
     * `'hybridSsr'`, never misreported as a generic configuration problem.
     */
    private async resolveEligibility(
        context: Readonly<CreateStaticWebAppContext>,
        iacFolder: vscode.Uri,
    ): Promise<StaticWebAppAutoDeployEligibility> {
        if (context.outputLocation !== undefined) {
            // Fresh wizard run -- PickBuildPresetStep already ran, so buildPresetSelection is trustworthy.
            if (context.buildPresetSelection === 'nextjs') {
                return 'hybridSsr';
            }
            return canAzdDeployStaticWebApp(context.outputLocation) ? 'supported' : 'invalidServiceConfig';
        }

        // Hydrated project -- outputLocation (and buildPresetSelection) were never captured
        // this run. Derive both signals from the existing service instead of assuming either.
        const serviceConfig = await getStaticWebAppServiceConfig(this.azd, this.code, iacFolder);
        if (!serviceConfig) {
            return 'invalidServiceConfig';
        }

        // Detect the framework at the service's own project folder rather than scanning the
        // whole repository -- avoids false positives/negatives in a monorepo when a specific
        // project path is already known from azure.yaml. `project` is required (never assumed
        // to default to iacFolder) and must resolve to an existing directory following azd's
        // path semantics -- an invalid path is `'invalidServiceConfig'`, never a silent fallback
        // to scanning iacFolder itself.
        const projectFolder = await resolveStaticWebAppServiceProjectFolder(this.code, iacFolder, serviceConfig.project);
        if (!projectFolder) {
            return 'invalidServiceConfig';
        }

        const detection = await detectStaticWebAppProject(this.code, this.indexService, projectFolder);
        if (detection.primaryPresetId === 'nextjs') {
            return 'hybridSsr';
        }

        return serviceConfig.dist !== undefined && canAzdDeployStaticWebApp(serviceConfig.dist) ? 'supported' : 'invalidServiceConfig';
    }
}
