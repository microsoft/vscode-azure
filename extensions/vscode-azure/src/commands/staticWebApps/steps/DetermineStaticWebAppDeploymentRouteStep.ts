import { IVsCode, PromptStep } from '@microsoft/vscode-azure-utils';
import { inject, injectable } from 'inversify';
import type * as vscode from 'vscode';
import { IAzdService, MinAzdPipelineVersion } from '../../../azd/AzdService';
import { IGitRemoteService } from '../../../staticWebApps/GitRemoteService';
import type { CreateStaticWebAppContext } from '../CreateStaticWebAppContext';
import { hasConflictingProviderWorkflow, getStaticWebAppServiceDist } from '../deploymentRouting';
import { canAzdDeployStaticWebApp } from './locationUtils';

/**
 * Silently routes Static Web Apps deployment during creation, without ever
 * showing UI (modeled on {@linkcode import('../../../azd/wizard/HydrateAzdInfoStep').HydrateAzdInfoStep HydrateAzdInfoStep}).
 * Runs last in `CreateStaticWebApp`'s prompt steps, once `iacFolder`,
 * `outputLocation` (when captured this run), and `buildPresetSelection` are
 * already settled.
 *
 * **Direct deployment support is determined first, before any routing
 * decision.** Two independent signals gate it:
 * - Next.js hybrid/SSR (`buildPresetSelection === 'nextjs'`, distinct from
 *   `'nextjs-export'`) is never deployable this way -- even if the user
 *   overrides the output location to a non-empty custom value, `azd deploy`
 *   still cannot serve server-rendered content, and the workflow generated by
 *   `azd pipeline config` only runs `azd deploy` too, so CI/CD cannot help
 *   either. Until a native SSR-capable workflow exists, both direct deploy
 *   *and* CI/CD are treated as unavailable for this shape.
 * - Whether the artifact directory is distinct from source
 *   (`canAzdDeployStaticWebApp`). For a **fresh** wizard run this reads
 *   `context.outputLocation` directly. For an **already-hydrated** project
 *   (`OutputLocationStep` skips prompting once `infra/main.bicep` already
 *   exists, so `outputLocation` is never captured this run), it is derived
 *   instead from the existing `azure.yaml`'s `host: staticwebapp` service
 *   `dist` -- a hydrated project must never be blanket-classified as
 *   unsupported just because this run didn't ask about output location. If no
 *   such service can be found at all (absent, unreadable, or an invalid
 *   `dist` -- missing/non-string/empty/`.`/`/`), eligibility is **not**
 *   granted: there is no valid deploy target to route direct deploy or CI/CD
 *   against, so this is treated the same as any other unsupported artifact
 *   shape. Eligibility is only ever derived from a positively-found, valid
 *   service.
 *
 * Decision (mutually exclusive):
 * 1. Neither direct deploy nor CI/CD is possible (either gate above) --
 *    explicitly forces `deploy: false` and sets
 *    {@linkcode CreateStaticWebAppContext.deploymentUnsupportedArtifact} so
 *    `CreateStaticWebApp` shows one honest "provisioned only" message instead
 *    of silently doing nothing or attempting a deploy that cannot work. This
 *    is a defensive, explicit suppression -- it does not rely on
 *    `OutputLocationStep`'s existing (still correct) gating as an implicit
 *    assumption, and it never even inspects the Git remote (irrelevant here).
 * 2. Direct deployment is supported, and a supported/pushed Git remote, a
 *    sufficient `azd` version, and no conflicting workflow for the other
 *    provider are all true -- sets `deploy: false` and
 *    {@linkcode CreateStaticWebAppContext.deploymentRoute}. `AzdDeployStep` is
 *    naturally skipped by the `deploy: false` merge; no changes to that
 *    shared step are needed.
 * 3. Direct deployment is supported, but CI/CD is not currently eligible
 *    (missing/unsupported remote, unpushed branch, `azd` too old, or a
 *    provider conflict) -- returns `{}`, retaining whatever `deploy` already
 *    was (`true`), so `AzdDeployStep` runs direct deploy exactly as it does
 *    today. This is the case (and the only case) where silently falling back
 *    to direct deploy is valid.
 */
@injectable()
export class DetermineStaticWebAppDeploymentRouteStep extends PromptStep<CreateStaticWebAppContext> {
    public constructor(
        @inject(IVsCode) private readonly code: IVsCode,
        @inject(IGitRemoteService) private readonly gitRemote: IGitRemoteService,
        @inject(IAzdService) private readonly azd: IAzdService,
    ) {
        super();
    }

    public override shouldPrompt(context: Readonly<CreateStaticWebAppContext>): boolean {
        return context.job === 'deploy' && !!context.iacFolder;
    }

    public async prompt(context: Readonly<CreateStaticWebAppContext>): Promise<Partial<CreateStaticWebAppContext>> {
        // shouldPrompt guarantees iacFolder is set.
        // eslint-disable-next-line @typescript-eslint/no-non-null-assertion
        const iacFolder = context.iacFolder!;

        const isHybridSsr = context.buildPresetSelection === 'nextjs';
        const canAutoDeploy = !isHybridSsr && await this.resolveCanAutoDeploy(context, iacFolder);

        if (!canAutoDeploy) {
            // Neither direct deploy nor CI/CD works for this artifact shape --
            // the Git remote is irrelevant, so it's never even inspected.
            return { deploy: false, deploymentUnsupportedArtifact: true };
        }

        const remote = await this.gitRemote.getRemoteInfo(iacFolder);
        if (!remote || remote.provider === 'unsupported' || !remote.hasUpstream) {
            return {};
        }
        if (!await this.azd.checkVersion(MinAzdPipelineVersion)) {
            return {};
        }
        if (await hasConflictingProviderWorkflow(this.code, iacFolder, remote.provider)) {
            return {};
        }

        return {
            deploy: false,
            deploymentRoute: { provider: remote.provider, repositoryUrl: remote.url, branch: remote.branch },
        };
    }

    /**
     * Determines whether the artifact directory is distinct from source.
     * Prefers `context.outputLocation` (set this run by `OutputLocationStep`);
     * falls back to the existing `azure.yaml` SWA service's `dist` for an
     * already-hydrated project where `outputLocation` was never captured.
     *
     * An absent, unreadable, or invalid service (no `host: staticwebapp`
     * entry at all, or one with a missing/non-string/empty/`.`/`/` `dist`) is
     * **ineligible** -- there is no valid deploy target to configure either
     * direct deploy or CI/CD against, so this must never be treated as
     * eligible by default. Eligibility is only ever granted when a valid
     * service is positively found.
     */
    private async resolveCanAutoDeploy(context: Readonly<CreateStaticWebAppContext>, iacFolder: vscode.Uri): Promise<boolean> {
        if (context.outputLocation !== undefined) {
            return canAzdDeployStaticWebApp(context.outputLocation);
        }

        const dist = await getStaticWebAppServiceDist(this.azd, this.code, iacFolder);
        return dist !== undefined && canAzdDeployStaticWebApp(dist);
    }
}
